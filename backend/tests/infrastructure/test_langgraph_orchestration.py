class TestFanOutResilience:
    """One failing specialist must not take the whole session down."""

    async def test_one_failing_specialist_leaves_the_others_intact(self):
        fake = FakeLLMProvider()

        class OneAgentFailsLLM:
            """Fails only vint's proposal call; everyone else uses the fake."""

            async def complete(self, request: LLMRequest) -> LLMResponse:
                # "You are Vint" is unique to vint's own call; triage says
                # "You are Leslie" (it only lists vint=networking in passing).
                if "you are vint" in request.system.lower():
                    raise RuntimeError("simulated provider failure for vint")
                return await fake.complete(request)

        deps = CrewSessionDeps(
            llm=OneAgentFailsLLM(),
            knowledge=CuratedCatalogKnowledgeSource(),
            repo=None,  # type: ignore[arg-type]
            events=RecordingEventPublisher(),
        )

        session = await run_graph("Serverless document pipeline", deps)

        # The run completes with the four survivors — not a crash, not zero.
        agents = {p.agent for p in session.proposals}
        assert agents == {"alan", "edgar", "hedy", "grace"}
        assert session.final_plan is not None


class TestDebateConflictPath:
    """R2/R4/R7 — the default `FakeLLMProvider` deterministically produces a
    strong conflict: `CrossReviewer` dispatches to `_REVIEW_TEMPLATE`
    (grace -> alan, challenge names "Amazon ECS with Fargate"), and alan's
    canned original proposal rejected "Amazon ECS" — a real strong conflict
    per `has_strong_conflict` (design §5.6). This is the "at least one
    visible debate, guaranteed" path the fake provider is built for.
    """

    async def test_conflict_triggers_exactly_one_reproposal(self, deps):
        session = await run_graph("E-commerce backend with high traffic", deps)

        assert len(session.reviews) == 1
        assert session.reviews[0].reviewer == "grace"
        assert session.reviews[0].target_agent == "alan"

        alan_proposal = next(p for p in session.proposals if p.agent == "alan")
        # Alan's canned ORIGINAL proposal has "AWS Lambda" in services and
        # "Amazon ECS: ..." in alternatives_rejected — the re-proposal flips
        # both (design §5.6, `_RE_PROPOSAL_RESPONSES["alan"]`).
        assert alan_proposal.services == ["Amazon ECS", "AWS Fargate", "Amazon API Gateway"]
        assert "AWS Lambda" not in alan_proposal.services
        assert any("Lambda" in a for a in alan_proposal.alternatives_rejected)

    async def test_conflict_never_two_reproposals(self, deps):
        """Topological bound (D5): `re_propose` never edges back to
        `review_round`, so exactly one review round runs no matter what.
        """
        session = await run_graph("E-commerce backend with high traffic", deps)
        assert len(session.reviews) == 1

    async def test_conflict_preserves_five_proposals(self, deps):
        """`re_propose` REPLACES alan's proposal by index (D6) — it must
        never append a 6th proposal or leave two entries for "alan".
        """
        session = await run_graph("E-commerce backend with high traffic", deps)
        assert len(session.proposals) == 5
        agents = [p.agent for p in session.proposals]
        assert agents.count("alan") == 1
        assert {p.agent for p in session.proposals} == {"alan", "edgar", "hedy", "grace", "vint"}

    async def test_conflict_emits_reproposal_event_for_target(self, deps):
        """A re-proposal must be visible in the event stream — its message
        must differ from the plain review-acknowledgement text the old
        hardcode used, and from a fresh initial-proposal event.
        """
        session = await run_graph("E-commerce backend with high traffic", deps)
        alan_events_after_review = [
            e for e in session.events
            if e.agent == "alan" and "Amazon ECS" in e.message
        ]
        assert len(alan_events_after_review) >= 1


class _NoConflictReviewLLMProvider:
    """Delegates every call to a real `FakeLLMProvider`, EXCEPT the
    cross-reviewer step, whose canned challenge is rewritten to name no
    service that the target (`edgar`) rejected. `has_strong_conflict` must
    then be False, and the graph must skip `re_propose` entirely (R4).
    """

    def __init__(self) -> None:
        self._delegate = FakeLLMProvider()

    async def complete(self, request: LLMRequest) -> LLMResponse:
        if "cross-reviewer" in request.system.lower():
            text = (
                "REVIEW:\n"
                "REVIEWER: hedy\n"
                "TARGET: edgar\n"
                "CHALLENGE: Consider adding a read replica for lower regional latency.\n"
                "TRADE_OFF: Slightly higher operational complexity for lower latency\n"
            )
            return LLMResponse(text=text, model=request.model)
        return await self._delegate.complete(request)


class TestDebateNoConflictPath:
    """R4 — when the review's challenge does not name a service the target
    explicitly rejected, `has_strong_conflict` is False and the graph must
    route straight to `leslie_consolidate`: zero re-proposals, proposals
    left exactly as the specialists first produced them.
    """

    @pytest.fixture
    def no_conflict_deps(self) -> CrewSessionDeps:
        return CrewSessionDeps(
            llm=_NoConflictReviewLLMProvider(),
            knowledge=CuratedCatalogKnowledgeSource(),
            repo=None,  # type: ignore[arg-type]  # graph doesn't persist
            events=RecordingEventPublisher(),
        )

    async def test_no_conflict_skips_reproposal(self, no_conflict_deps):
        session = await run_graph("Multi-region read replica setup", no_conflict_deps)

        assert len(session.reviews) == 1
        assert session.reviews[0].reviewer == "hedy"
        assert session.reviews[0].target_agent == "edgar"

        edgar_proposal = next(p for p in session.proposals if p.agent == "edgar")
        # Untouched: identical to FakeLLMProvider's canned ORIGINAL — no
        # re-propose ran, so nothing replaced it.
        assert edgar_proposal.services == ["Amazon DynamoDB", "Amazon S3", "Amazon ElastiCache"]
        assert edgar_proposal.alternatives_rejected == [
            "Amazon RDS: Requires cluster management; relational model may not fit all use cases",
            "Amazon Aurora: Higher cost for the scale of this workload",
        ]

    async def test_no_conflict_emits_no_reproposal_event(self, no_conflict_deps):
        session = await run_graph("Multi-region read replica setup", no_conflict_deps)
        reproposal_events = [
            e for e in session.events
            if e.agent == "edgar" and "Reconsidering" in e.message
        ]
        assert reproposal_events == []

    async def test_no_conflict_proposal_count_unchanged(self, no_conflict_deps):
        session = await run_graph("Multi-region read replica setup", no_conflict_deps)
        assert len(session.proposals) == 5
        assert {p.agent for p in session.proposals} == {"alan", "edgar", "hedy", "grace", "vint"}


class TestDebateEndToEndFake:
    """R7/R12 — fake mode always shows a debate, deterministically and
    reproducibly across runs. NOTE: `final_plan.services` itself is NOT
    asserted to contain the contested service ("Amazon ECS"): FakeLLMProvider
    dispatches the consolidate response purely by `request.system`
    (design §5.6/A9) — Leslie's `_CONSOLIDATE_SYSTEM` never changes, so its
    canned SERVICES line is identical regardless of which proposals were
    actually passed in. What IS falsifiable end-to-end is that the SESSION's
    own proposal for the debated agent reflects the revision, not the
    pre-debate canned original, and that this holds reproducibly.
    """

    async def test_final_plan_produced_after_debate(self, deps):
        session = await run_graph("E-commerce backend with high traffic", deps)
        assert session.final_plan is not None
        assert session.final_plan.summary != ""
        assert len(session.final_plan.services) >= 1

    async def test_session_proposal_reflects_revision_not_original(self, deps):
        session = await run_graph("E-commerce backend with high traffic", deps)
        alan_proposal = next(p for p in session.proposals if p.agent == "alan")
        original_alan_services = ["AWS Lambda", "Amazon API Gateway"]
        assert alan_proposal.services != original_alan_services

    async def test_fake_debate_is_deterministic_across_runs(self, deps):
        """R7 scenario: running twice must produce an identical debate outcome."""
        session1 = await run_graph("E-commerce backend with high traffic", deps)
        session2 = await run_graph("E-commerce backend with high traffic", deps)

        for session in (session1, session2):
            assert len(session.reviews) == 1
            alan_proposal = next(p for p in session.proposals if p.agent == "alan")
            assert alan_proposal.services == ["Amazon ECS", "AWS Fargate", "Amazon API Gateway"]


class TestRunGraphSessionId:
    """run_graph must honour a caller-supplied session_id.

    The route pre-allocates the id returned to the client and the SSE queue is
    keyed by that id. If the graph mints its own id, every event lands in the
    wrong queue and the live stream is empty.
    """

    async def test_run_graph_uses_provided_session_id(self, deps):
        session = await run_graph("Build a serverless pipeline", deps, session_id="fixed-id-123")
        assert session.session_id == "fixed-id-123"

    async def test_run_graph_publishes_under_provided_session_id(self, deps):
        await run_graph("Real-time data ingestion", deps, session_id="fixed-id-456")
        published_ids = {sid for sid, _ in deps.events.published_events}
        assert published_ids == {"fixed-id-456"}

    async def test_run_graph_generates_id_when_omitted(self, deps):
        """Backward compatible: omitting session_id still works."""
        session = await run_graph("Multi-tenant SaaS backend", deps)
        assert isinstance(session.session_id, str)
        assert len(session.session_id) > 0
